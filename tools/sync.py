#!/usr/bin/env python3
"""Builds dist/ and every manifest from core/. Edit core/, never dist/.

All hand-written settings live in core/config.json: name, version, repo,
description, guard order and each Claude mod's manifest. The owner comes from the
repo URL. Each agent gets rules/rules.md, rules/mini.md and, when it exists,
rules/<agent>.md. Real code stays hand-written in core/hooks and core/mods.

dist/ is committed because a GitHub install reads the repo as is. It holds real
files, not symlinks: Claude Code copies a plugin to a cache and cannot follow
links out of it. The root package.json and .claude-plugin/marketplace.json are
generated too, because OpenCode, pi and Claude Code look for them at the root.
"""
import json
import re
import shutil
from pathlib import Path

root = Path(__file__).resolve().parent.parent
core, dist = root / "core", root / "dist"
project = json.loads((core / "config.json").read_text())
owner = project["repository"].rstrip("/").split("/")[-2]
GENERATED = "<!-- Generated by tools/sync.py. Edit core/ instead. -->"
guards = project["guards"]
guard_files = ["_common.sh", *(f"{name}.sh" for name in guards)]
DEV_ONLY = shutil.ignore_patterns("*.test.ts", ".DS_Store", "types", "tools")


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def strip_frontmatter(path: Path) -> str:
    text = re.sub(r"^---\r?\n[\s\S]*?\r?\n---\r?\n?", "", path.read_text(encoding="utf-8"), count=1)
    return text.strip() + "\n"


def write_rules(agent: str, target: Path) -> None:
    files = [core / "rules" / "rules.md", core / "rules" / "mini.md", core / "rules" / f"{agent}.md"]
    rules = [strip_frontmatter(path) for path in files if path.exists()]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(GENERATED + "\n\n" + "\n".join(rules))


def copy_guards(target: Path) -> None:
    target.mkdir(parents=True, exist_ok=True)
    for name in guard_files:
        shutil.copy(core / "hooks" / name, target / name)


def build_claude() -> None:
    claude = dist / "claude"
    plugin = claude / project["name"]
    for folder, name in [("context", "rules.md"), ("output-styles", "mini.md")]:
        (plugin / folder).mkdir(parents=True)
        shutil.copy(core / "rules" / name, plugin / folder / name)
    shutil.copytree(core / "skills", plugin / "skills")
    copy_guards(plugin / "hooks")
    shutil.copy(core / "hooks" / "export-scratch.sh", plugin / "hooks" / "export-scratch.sh")

    write_json(plugin / ".claude-plugin" / "plugin.json", {
        "name": project["name"], "displayName": project["displayName"],
        "version": project["version"], "description": project["description"], "author": {"name": owner},
    })
    rules_check = (
        'f="${CLAUDE_PLUGIN_ROOT}/context/rules.md"; test -s "$f" || '
        '{ echo "' + project["name"] + ': $f is missing or empty" >&2; exit 2; }; cat "$f"'
    )
    command = lambda text: {"type": "command", "command": text}
    write_json(plugin / "hooks" / "hooks.json", {"hooks": {
        "SessionStart": [{"hooks": [command(rules_check), command('"${CLAUDE_PLUGIN_ROOT}/hooks/export-scratch.sh"')]}],
        "PreToolUse": [{"matcher": "Bash", "hooks": [command(f'"${{CLAUDE_PLUGIN_ROOT}}/hooks/{name}.sh"') for name in guards]}],
    }})

    for name, manifest in project["mods"].items():
        shutil.copytree(core / "mods" / name, claude / name, ignore=DEV_ONLY)
        write_json(claude / name / ".claude-plugin" / "plugin.json", {"name": name, "version": project["version"], "author": {"name": owner}, **manifest})

    entries = []
    for folder in sorted(claude.iterdir()):
        manifest = json.loads((folder / ".claude-plugin" / "plugin.json").read_text())
        entries.append({"name": manifest["name"], "source": f"./dist/claude/{folder.name}", "description": manifest["description"]})
    write_json(root / ".claude-plugin" / "marketplace.json", {
        "name": project["name"], "metadata": {"version": project["version"]},
        "owner": {"name": owner}, "plugins": entries,
    })


def build_antigravity() -> None:
    agy = dist / "antigravity"
    write_json(agy / "plugin.json", {"name": project["name"], "version": project["version"], "repository": project["repository"]})
    write_json(agy / "hooks.json", {f"{project['name']}-guards": {"PreToolUse": [{
        "matcher": "run_command",
        "hooks": [{"type": "command", "command": f"./hooks/{name}.sh"} for name in guards],
    }]}})
    shutil.copytree(core / "skills", agy / "skills")
    copy_guards(agy / "hooks")
    write_rules("antigravity", agy / "rules" / "AGENTS.md")


def build_opencode() -> None:
    opencode = dist / "opencode"
    shutil.copytree(core / "mods" / "opencode", opencode, ignore=DEV_ONLY)
    shutil.copytree(core / "skills", opencode / "skills")
    write_rules("opencode", opencode / "context.md")


def build_pi() -> None:
    shutil.copytree(core / "skills", dist / "pi" / "skills")
    write_rules("pi", dist / "pi" / "APPEND_SYSTEM.md")


def write_package_json() -> None:
    write_json(root / "package.json", {
        "name": project["name"], "version": project["version"], "description": project["description"],
        "repository": project["repository"], "type": "module", "keywords": ["pi-package"],
        "pi": {"skills": ["./dist/pi/skills"]},
        "exports": {".": "./dist/opencode/index.ts"},
        "files": ["dist/opencode", "dist/pi"],
        "dependencies": {"@opencode/plugin": "latest"},
    })


shutil.rmtree(dist, ignore_errors=True)
build_claude()
build_antigravity()
build_opencode()
build_pi()
write_package_json()
