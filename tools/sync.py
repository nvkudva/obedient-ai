#!/usr/bin/env python3
"""Builds dist/ and every manifest from core/. Edit core/, never dist/.

The only hand-written facts are in core/project.json (name, version, owner, repo,
description, guard order). Manifests, hook wiring and the marketplace file are
generated from it. Real code stays hand-written: core/configs/ holds
export-scratch.sh and the OpenCode adapter, core/mods/ holds the Claude Code mods.

dist/ is committed because a GitHub install reads the repo as is. It holds real
files, not symlinks: Claude Code copies a plugin to a cache and cannot follow
links out of it.
"""
import json
import re
import shutil
from pathlib import Path

root = Path(__file__).resolve().parent.parent
core, dist = root / "core", root / "dist"
project = json.loads((core / "project.json").read_text())
GENERATED = "<!-- Generated by tools/sync.py. Edit core/ instead. -->"
guards = project["guards"]
guard_files = ["_common.sh", *(f"{name}.sh" for name in guards)]


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def strip_frontmatter(path: Path) -> str:
    text = re.sub(r"^---\r?\n[\s\S]*?\r?\n---\r?\n?", "", path.read_text(encoding="utf-8"), count=1)
    return text.strip() + "\n"


def copy_guards(target: Path) -> None:
    target.mkdir(parents=True, exist_ok=True)
    for name in guard_files:
        shutil.copy(core / "guards" / name, target / name)


def copy_plugin(source: Path, target: Path) -> None:
    shutil.copytree(source, target, ignore=shutil.ignore_patterns("*.test.ts", ".DS_Store", "types"))


def stamp_version(manifest_path: Path) -> None:
    manifest = json.loads(manifest_path.read_text())
    write_json(manifest_path, {**manifest, "version": project["version"]})


def build_claude() -> None:
    claude = dist / "claude"
    plugin = claude / project["name"]
    copy_plugin(core / "configs" / "claude" / project["name"], plugin)
    shutil.copytree(core / "context", plugin / "context")
    shutil.copytree(core / "output-styles", plugin / "output-styles")
    shutil.copytree(core / "skills", plugin / "skills")
    copy_guards(plugin / "hooks")

    write_json(plugin / ".claude-plugin" / "plugin.json", {
        "name": project["name"], "displayName": project["displayName"],
        "version": project["version"], "description": project["description"],
    })
    rules_check = (
        'f="${CLAUDE_PLUGIN_ROOT}/context/rules.md"; test -s "$f" || '
        '{ echo "' + project["name"] + ': $f is missing or empty" >&2; exit 2; }; cat "$f"'
    )
    command = lambda text: {"type": "command", "command": text}
    write_json(plugin / "hooks" / "hooks.json", {"hooks": {
        "SessionStart": [{"hooks": [command(rules_check), command('"${CLAUDE_PLUGIN_ROOT}/hooks/export-scratch.sh"')]}],
        "PreToolUse": [{"matcher": "Bash", "hooks": [command(f'"${{CLAUDE_PLUGIN_ROOT}}/hooks/{name}.sh"') for name in guards]}],
    }})

    for mod in sorted((core / "mods").iterdir()):
        copy_plugin(mod, claude / mod.name)
        stamp_version(claude / mod.name / ".claude-plugin" / "plugin.json")
    shutil.rmtree(claude / "token-saver" / "tools", ignore_errors=True)

    entries = []
    for folder in sorted(claude.iterdir()):
        manifest = json.loads((folder / ".claude-plugin" / "plugin.json").read_text())
        entries.append({"name": manifest["name"], "source": f"./dist/claude/{folder.name}", "description": manifest["description"]})
    write_json(root / ".claude-plugin" / "marketplace.json", {
        "name": project["name"], "metadata": {"version": project["version"]},
        "owner": {"name": project["owner"]}, "plugins": entries,
    })


def build_antigravity() -> None:
    agy = dist / "antigravity"
    write_json(agy / "plugin.json", {"name": project["name"], "version": project["version"], "repository": project["repository"]})
    write_json(agy / "hooks.json", {f"{project['name']}-guards": {"PreToolUse": [{
        "matcher": "run_command",
        "hooks": [{"type": "command", "command": f"./hooks/{name}.sh"} for name in guards],
    }]}})
    shutil.copytree(core / "skills", agy / "skills")
    copy_guards(agy / "hooks")
    rules = [strip_frontmatter(core / "context" / "rules.md"), strip_frontmatter(core / "output-styles" / "mini.md"),
             strip_frontmatter(core / "context" / "rules-antigravity.md")]
    (agy / "rules").mkdir()
    (agy / "rules" / "AGENTS.md").write_text(GENERATED + "\n\n" + "\n".join(rules))


def build_opencode_and_pi() -> None:
    (dist / "opencode").mkdir()
    shutil.copy(core / "configs" / "opencode" / "index.ts", dist / "opencode" / "index.ts")
    (dist / "pi").mkdir()
    rules = [strip_frontmatter(core / "context" / "rules.md"), strip_frontmatter(core / "output-styles" / "mini.md")]
    (dist / "pi" / "APPEND_SYSTEM.md").write_text(GENERATED + "\n\n" + "\n".join(rules))


def stamp_package_version() -> None:
    path = root / "package.json"
    path.write_text(re.sub(r'("version":\s*")[^"]*(")', rf'\g<1>{project["version"]}\g<2>', path.read_text(), count=1))


shutil.rmtree(dist, ignore_errors=True)
build_claude()
build_antigravity()
build_opencode_and_pi()
stamp_package_version()
