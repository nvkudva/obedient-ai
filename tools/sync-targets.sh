#!/usr/bin/env bash
# Generates agent-specific rule bundles from the single source of truth in
# obedient-ai/context/ and obedient-ai/output-styles/, and ensures symlinks exist.
set -euo pipefail

cd "$(dirname "$0")/.."

strip_frontmatter() {
  python3 -c '
import re, sys
text = open(sys.argv[1], encoding="utf-8").read()
text = re.sub(r"^---\r?\n[\s\S]*?\r?\n---\r?\n?", "", text, count=1)
sys.stdout.write(text.strip() + "\n")
' "$1"
}

mkdir -p antigravity/rules pi

{
  printf '<!-- Generated by tools/sync-targets.sh. Edit obedient-ai/context/ or obedient-ai/output-styles/ instead. -->\n\n'
  strip_frontmatter obedient-ai/context/rules.md
  printf '\n'
  strip_frontmatter obedient-ai/output-styles/mini.md
  printf '\n'
  strip_frontmatter obedient-ai/context/rules-antigravity.md
} > antigravity/rules/AGENTS.md

{
  printf '<!-- Generated by tools/sync-targets.sh. Edit obedient-ai/context/ or obedient-ai/output-styles/ instead. -->\n\n'
  strip_frontmatter obedient-ai/context/rules.md
  printf '\n'
  strip_frontmatter obedient-ai/output-styles/mini.md
} > pi/APPEND_SYSTEM.md

rm -rf antigravity/hooks
mkdir -p antigravity/hooks
for f in _common.sh block-dangerous-git.sh block-sleep.sh prefer-fast-tools.sh; do
  ln -sfn "../../obedient-ai/hooks/$f" "antigravity/hooks/$f"
done
ln -sfn ../obedient-ai/skills antigravity/skills
